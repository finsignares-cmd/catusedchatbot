// Offline retrieval evaluation: old logic (7cfea65) vs new
// (functions/retrieval.js) on the same catalogue snapshot (tasks.md T9).
// Usage: node eval/run_eval.mjs   -> writes eval/results.md and results.json
import {readFileSync, writeFileSync} from "node:fs";
import {performance} from "node:perf_hooks";
import {legacyRetrieve} from "./legacy_retrieval.js";
import {
  selectMachines, selectKnowledge, machineLocation, idState,
} from "../functions/retrieval.js";
import {machineForPrompt} from "../functions/prompt.js";

const here = (p) => new URL(p, import.meta.url);
const read = (p) => JSON.parse(readFileSync(here(p), "utf8"));
const machines = read("../data/snapshot/machines.json");
const knowledge = read("../data/snapshot/knowledge.json");
const {queries} = read("./queries.json");
const byId = Object.fromEntries(machines.map((m) => [m.machineId, m]));
const REPS = 200;

/**
 * Average wall time of a function, in milliseconds.
 * @param {Function} fn Function.
 * @return {number} ms.
 */
function time(fn) {
  const t0 = performance.now();
  for (let i = 0; i < REPS; i++) fn();
  return (performance.now() - t0) / REPS;
}

const runs = {legacy: [], fixed: []};
for (const q of queries) {
  const old = legacyRetrieve(q.text, "", machines, knowledge);
  runs.legacy.push({q, ids: old.machineIds, flagged: [],
    contextChars: old.contextChars, knowledgeCount: old.knowledgeCount,
    ms: time(() => legacyRetrieve(q.text, "", machines, knowledge))});

  const sel = selectMachines(q.text, machines);
  const kn = selectKnowledge(q.text, knowledge);
  const ctx = JSON.stringify(sel.matches.map(machineForPrompt)) +
    JSON.stringify(sel.conflicts.map(machineForPrompt)) +
    JSON.stringify(kn.map((k) => ({title: k.title, content: k.content})));
  runs.fixed.push({q, ids: sel.matches.map((m) => m.machineId),
    flagged: sel.conflicts.map((m) => m.machineId),
    contextChars: ctx.length, knowledgeCount: kn.length,
    ms: time(() => {
      selectMachines(q.text, machines); selectKnowledge(q.text, knowledge);
    })});
}

/**
 * A machine offered for a location query whose location field or ID
 * suffix is not the requested state.
 * @param {string} id Machine ID.
 * @param {string} state Requested state.
 * @return {boolean} Wrong location.
 */
function wrongPlace(id, state) {
  const m = byId[id];
  return machineLocation(m).state !== state || idState(m) !== state;
}

/**
 * Aggregate metrics of one system.
 * @param {Array<Object>} rows Per-query results.
 * @return {Object} Metrics.
 */
function metrics(rows) {
  let tp = 0; let fp = 0; let fn = 0; let exact = 0; let wrong = 0;
  let locQueriesWithWrong = 0;
  for (const r of rows) {
    const exp = new Set(r.q.expected);
    const got = new Set(r.ids);
    const hit = [...got].filter((x) => exp.has(x)).length;
    tp += hit; fp += got.size - hit; fn += exp.size - hit;
    if (hit === exp.size && got.size === exp.size) exact++;
    if (r.q.type === "location") {
      const w = [...got].filter((id) => wrongPlace(id, r.q.state)).length;
      wrong += w;
      if (w) locQueriesWithWrong++;
    }
  }
  const avg = (k) => rows.reduce((s, r) => s + r[k], 0) / rows.length;
  return {
    queries: rows.length,
    precision: tp / ((tp + fp) || 1),
    recall: tp / ((tp + fn) || 1),
    exactMatch: exact,
    wrongLocationMachines: wrong,
    locationQueriesWithWrongMachine: locQueriesWithWrong,
    locationQueries: rows.filter((r) => r.q.type === "location").length,
    avgMachinesInContext: rows.reduce((s, r) => s + r.ids.length, 0) /
      rows.length,
    avgContextChars: avg("contextChars"),
    avgKnowledgeDocs: avg("knowledgeCount"),
    avgRetrievalMs: avg("ms"),
  };
}

const L = metrics(runs.legacy);
const F = metrics(runs.fixed);
const pct = (x) => `${(x * 100).toFixed(1)} %`;
const n1 = (x) => x.toFixed(1);
const date = new Date().toISOString().slice(0, 10);

const lines = [
  "# Retrieval evaluation — measured results",
  "",
  `Generated by \`node eval/run_eval.mjs\` on ${date} (Node ${process.version}).`,
  `Data: \`data/snapshot/\` (${machines.length} machines, ${knowledge.length} knowledge docs).`,
  `Queries: \`eval/queries.json\` (${queries.length} labelled, EN + ES).`,
  "\"Old\" = retrieval of commit 7cfea65 (verbatim copy in `eval/legacy_retrieval.js`),",
  "new conversation (no history). \"New\" = `functions/retrieval.js`.",
  "",
  "| Metric | Old | New |",
  "|---|---|---|",
  `| Precision (machine IDs offered to the model) | ${pct(L.precision)} | ${pct(F.precision)} |`,
  `| Recall | ${pct(L.recall)} | ${pct(F.recall)} |`,
  `| Queries with exactly the right machines | ${L.exactMatch} / ${L.queries} | ${F.exactMatch} / ${F.queries} |`,
  `| Location queries that offer a wrong-location machine | ${L.locationQueriesWithWrongMachine} / ${L.locationQueries} | ${F.locationQueriesWithWrongMachine} / ${F.locationQueries} |`,
  `| Wrong-location machines offered (total) | ${L.wrongLocationMachines} | ${F.wrongLocationMachines} |`,
  `| Avg. machines in context per query | ${n1(L.avgMachinesInContext)} | ${n1(F.avgMachinesInContext)} |`,
  `| Avg. knowledge docs in context | ${n1(L.avgKnowledgeDocs)} | ${n1(F.avgKnowledgeDocs)} |`,
  `| Avg. context size (characters) | ${Math.round(L.avgContextChars)} | ${Math.round(F.avgContextChars)} |`,
  `| Avg. retrieval time (ms, ${REPS} runs) | ${L.avgRetrievalMs.toFixed(3)} | ${F.avgRetrievalMs.toFixed(3)} |`,
  "",
  "Records with contradictory ID/location are not counted as offered by the",
  "new logic: they go to the separate UNCONFIRMED LOCATION block of the prompt.",
  "",
  "## Per query",
  "",
  "| ID | Query | Expected | Old | New | New: flagged |",
  "|---|---|---|---|---|---|",
];
for (let i = 0; i < queries.length; i++) {
  const q = queries[i];
  const o = runs.legacy[i];
  const f = runs.fixed[i];
  const fmt = (ids) => ids.length > 4 ? `${ids.length} machines` :
    (ids.join(", ") || "—");
  const mark = (ids) => {
    const ok = ids.length === q.expected.length &&
      ids.every((x) => q.expected.includes(x));
    return `${ok ? "✅" : "❌"} ${fmt(ids)}`;
  };
  lines.push(`| ${q.id} | ${q.text} | ${fmt(q.expected)} | ` +
    `${mark(o.ids)} | ${mark(f.ids)} | ${f.flagged.join(", ") || "—"} |`);
}
writeFileSync(here("./results.md"), lines.join("\n") + "\n");
writeFileSync(here("./results.json"), JSON.stringify({date, old: L, new: F,
  perQuery: queries.map((q, i) => ({id: q.id, text: q.text,
    expected: q.expected, old: runs.legacy[i].ids, new: runs.fixed[i].ids,
    flagged: runs.fixed[i].flagged}))}, null, 2) + "\n");
console.log(lines.slice(0, 20).join("\n"));
